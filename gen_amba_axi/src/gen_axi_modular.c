int gen_axi4_address_decoder(unsigned int numM, unsigned int numS, unsigned int widthAD, FILE *fo) {
    
    fprintf(fo, "//--------------------------------------------------------\n");
    fprintf(fo, "// AXI4 Address Decoder Module\n");
    fprintf(fo, "// Decodes addresses and generates slave select signals\n");
    fprintf(fo, "// AMBA AXI4 Protocol Compliant\n");
    fprintf(fo, "// Generated by Modular AXI Generator\n");
    fprintf(fo, "//--------------------------------------------------------\n");
    fprintf(fo, "`timescale 1ns/1ps\n\n");
    
    fprintf(fo, "module axi4_address_decoder #(\n");
    fprintf(fo, "    parameter NUM_MASTER  = %d,\n", numM);
    fprintf(fo, "    parameter NUM_SLAVE   = %d,\n", numS);
    fprintf(fo, "    parameter ADDR_WIDTH  = %d\n", widthAD);
    fprintf(fo, ")(\n");
    fprintf(fo, "    // Clock and Reset\n");
    fprintf(fo, "    input  wire                         aclk,\n");
    fprintf(fo, "    input  wire                         aresetn,\n\n");
    
    // Write address decode inputs from all masters
    fprintf(fo, "    // Write Address Decode Inputs (from masters)\n");
    for (unsigned int m = 0; m < numM; m++) {
        fprintf(fo, "    input  wire [ADDR_WIDTH-1:0]        m%d_awaddr,\n", m);
        fprintf(fo, "    input  wire                         m%d_awvalid,\n", m);
    }
    fprintf(fo, "\n");
    
    // Read address decode inputs from all masters  
    fprintf(fo, "    // Read Address Decode Inputs (from masters)\n");
    for (unsigned int m = 0; m < numM; m++) {
        fprintf(fo, "    input  wire [ADDR_WIDTH-1:0]        m%d_araddr,\n", m);
        fprintf(fo, "    input  wire                         m%d_arvalid,\n", m);
    }
    fprintf(fo, "\n");
    
    // Slave select outputs for each master
    fprintf(fo, "    // Slave Select Outputs (to interconnect)\n");
    for (unsigned int m = 0; m < numM; m++) {
        fprintf(fo, "    output wire [NUM_SLAVE-1:0]         m%d_aw_slave_sel,\n", m);
        fprintf(fo, "    output wire [NUM_SLAVE-1:0]         m%d_ar_slave_sel,\n", m);
    }
    fprintf(fo, "\n");
    
    fprintf(fo, "    // Address decode error signals\n");
    for (unsigned int m = 0; m < numM; m++) {
        fprintf(fo, "    output wire                         m%d_aw_decode_error,\n", m);
        fprintf(fo, "    output wire                         m%d_ar_decode_error,\n", m);
    }
    fprintf(fo, "\n");
    
    fprintf(fo, "    // Debug outputs\n");
    fprintf(fo, "    output wire [31:0]                  debug_decode_count,\n");
    fprintf(fo, "    output wire [31:0]                  debug_error_count\n");
    fprintf(fo, ");\n\n");
    
    // Slave address map parameters
    fprintf(fo, "    // Slave Address Map (256MB per slave)\n");
    for (unsigned int s = 0; s < numS; s++) {
        fprintf(fo, "    localparam [ADDR_WIDTH-1:0] SLAVE%d_BASE = %d'h%08X;\n", 
                s, widthAD, s * 0x10000000);
        fprintf(fo, "    localparam [ADDR_WIDTH-1:0] SLAVE%d_MASK = %d'h0FFFFFFF;\n", 
                s, widthAD);
    }
    fprintf(fo, "\n");
    
    // Internal registers for debug
    fprintf(fo, "    // Debug counters\n");
    fprintf(fo, "    reg [31:0] decode_count;\n");
    fprintf(fo, "    reg [31:0] error_count;\n\n");
    
    // Generate decode logic for each master
    for (unsigned int m = 0; m < numM; m++) {
        fprintf(fo, "    // Address decode logic for Master %d\n", m);
        fprintf(fo, "    reg [NUM_SLAVE-1:0] m%d_aw_sel_int;\n", m);
        fprintf(fo, "    reg [NUM_SLAVE-1:0] m%d_ar_sel_int;\n", m);
        fprintf(fo, "    reg m%d_aw_err_int, m%d_ar_err_int;\n\n", m, m);
        
        fprintf(fo, "    always @(*) begin\n");
        fprintf(fo, "        // Default values\n");
        fprintf(fo, "        m%d_aw_sel_int = {NUM_SLAVE{1'b0}};\n", m);
        fprintf(fo, "        m%d_ar_sel_int = {NUM_SLAVE{1'b0}};\n", m);
        fprintf(fo, "        m%d_aw_err_int = 1'b0;\n", m);
        fprintf(fo, "        m%d_ar_err_int = 1'b0;\n\n", m);
        
        fprintf(fo, "        // Write address decode for Master %d\n", m);
        fprintf(fo, "        if (m%d_awvalid) begin\n", m);
        for (unsigned int s = 0; s < numS; s++) {
            if (s == 0) {
                fprintf(fo, "            if ((m%d_awaddr & ~SLAVE%d_MASK) == SLAVE%d_BASE)\n", m, s, s);
            } else {
                fprintf(fo, "            else if ((m%d_awaddr & ~SLAVE%d_MASK) == SLAVE%d_BASE)\n", m, s, s);
            }
            fprintf(fo, "                m%d_aw_sel_int[%d] = 1'b1;\n", m, s);
        }
        fprintf(fo, "            else\n");
        fprintf(fo, "                m%d_aw_err_int = 1'b1;  // No slave matches\n", m);
        fprintf(fo, "        end\n\n");
        
        fprintf(fo, "        // Read address decode for Master %d\n", m);
        fprintf(fo, "        if (m%d_arvalid) begin\n", m);
        for (unsigned int s = 0; s < numS; s++) {
            if (s == 0) {
                fprintf(fo, "            if ((m%d_araddr & ~SLAVE%d_MASK) == SLAVE%d_BASE)\n", m, s, s);
            } else {
                fprintf(fo, "            else if ((m%d_araddr & ~SLAVE%d_MASK) == SLAVE%d_BASE)\n", m, s, s);
            }
            fprintf(fo, "                m%d_ar_sel_int[%d] = 1'b1;\n", m, s);
        }
        fprintf(fo, "            else\n");
        fprintf(fo, "                m%d_ar_err_int = 1'b1;  // No slave matches\n", m);
        fprintf(fo, "        end\n");
        fprintf(fo, "    end\n\n");
        
        // Assign outputs
        fprintf(fo, "    assign m%d_aw_slave_sel   = m%d_aw_sel_int;\n", m, m);
        fprintf(fo, "    assign m%d_ar_slave_sel   = m%d_ar_sel_int;\n", m, m);
        fprintf(fo, "    assign m%d_aw_decode_error = m%d_aw_err_int;\n", m, m);
        fprintf(fo, "    assign m%d_ar_decode_error = m%d_ar_err_int;\n\n", m, m);
    }
    
    // Debug counter logic
    fprintf(fo, "    // Debug counter logic\n");
    fprintf(fo, "    always @(posedge aclk or negedge aresetn) begin\n");
    fprintf(fo, "        if (!aresetn) begin\n");
    fprintf(fo, "            decode_count <= 32'd0;\n");
    fprintf(fo, "            error_count  <= 32'd0;\n");
    fprintf(fo, "        end else begin\n");
    fprintf(fo, "            // Count decode operations\n");
    fprintf(fo, "            decode_count <= decode_count + ");
    for (unsigned int m = 0; m < numM; m++) {
        if (m > 0) fprintf(fo, " + ");
        fprintf(fo, "(m%d_awvalid ? 1 : 0) + (m%d_arvalid ? 1 : 0)", m, m);
    }
    fprintf(fo, ";\n");
    fprintf(fo, "            \n");
    fprintf(fo, "            // Count decode errors\n");
    fprintf(fo, "            error_count <= error_count + ");
    for (unsigned int m = 0; m < numM; m++) {
        if (m > 0) fprintf(fo, " + ");
        fprintf(fo, "(m%d_aw_err_int ? 1 : 0) + (m%d_ar_err_int ? 1 : 0)", m, m);
    }
    fprintf(fo, ";\n");
    fprintf(fo, "        end\n");
    fprintf(fo, "    end\n\n");
    
    fprintf(fo, "    // Debug output assignments\n");
    fprintf(fo, "    assign debug_decode_count = decode_count;\n");
    fprintf(fo, "    assign debug_error_count  = error_count;\n\n");
    
    fprintf(fo, "endmodule\n");
    
    return 0;
}

